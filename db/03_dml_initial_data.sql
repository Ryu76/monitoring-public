-- 관리자에게 ROLE_SYSTEM_ADMIN 권한 부여
-- USER_ID = 1 (IDENTITY 자동 생성 가정) 및 ROLE_ID = 1 로 삽입
-- (실제 운영 시퀀스를 맞추기 위해 서브쿼리 사용 권장)
INSERT INTO SYS_USER_ROLE (USER_ID, ROLE_ID, CREATED_BY)
SELECT u.USER_ID, r.ROLE_ID, 'SYSTEM'
FROM SYS_USER u, SYS_ROLE r
WHERE u.LOGIN_ID = 'admin' AND r.ROLE_CODE = 'ROLE_SYSTEM_ADMIN';


-- 1. FK 제약조건
ALTER TABLE SYS_USER_ROLE ADD CONSTRAINT FK_USER_ROLE_UID FOREIGN KEY (USER_ID) REFERENCES SYS_USER(USER_ID);
ALTER TABLE SYS_USER_ROLE ADD CONSTRAINT FK_USER_ROLE_RID FOREIGN KEY (ROLE_ID) REFERENCES SYS_ROLE(ROLE_ID);

ALTER TABLE SYS_ROLE_PERMISSION ADD CONSTRAINT FK_ROLE_PERM_RID FOREIGN KEY (ROLE_ID) REFERENCES SYS_ROLE(ROLE_ID);
ALTER TABLE SYS_ROLE_PERMISSION ADD CONSTRAINT FK_ROLE_PERM_PID FOREIGN KEY (PERMISSION_ID) REFERENCES SYS_PERMISSION(PERMISSION_ID);

ALTER TABLE MON_AGENT ADD CONSTRAINT FK_AGENT_SERVER FOREIGN KEY (SERVER_ID) REFERENCES MON_SERVER(SERVER_ID);
ALTER TABLE MON_SERVER_STATUS_CURR ADD CONSTRAINT FK_SERVER_STATUS_CURR FOREIGN KEY (SERVER_ID) REFERENCES MON_SERVER(SERVER_ID);
ALTER TABLE MON_AGENT_STATUS_CURR ADD CONSTRAINT FK_AGENT_STATUS_CURR FOREIGN KEY (AGENT_ID) REFERENCES MON_AGENT(AGENT_ID);

ALTER TABLE MON_METRIC_CURR ADD CONSTRAINT FK_METRIC_CURR_SRV FOREIGN KEY (SERVER_ID) REFERENCES MON_SERVER(SERVER_ID);
ALTER TABLE MON_METRIC_CURR ADD CONSTRAINT FK_METRIC_CURR_METRIC FOREIGN KEY (METRIC_CODE) REFERENCES MON_METRIC_DEF(METRIC_CODE);

-- 2. 주요 조회용 인덱스
-- 이력 테이블은 조회 빈도가 높은 SERVER_ID, METRIC_CODE, 수집시간 등에 Local Index 생성을 권장
-- 여기서는 기본적으로 파티션된 테이블에 대한 인덱스 예시를 생성합니다.

CREATE INDEX IDX_MON_METRIC_HIST_01 ON MON_METRIC_HIST (SERVER_ID, METRIC_CODE, COLLECTED_AT);
CREATE INDEX IDX_MON_METRIC_HIST_02 ON MON_METRIC_HIST (SERVER_ID, COLLECTED_AT);
CREATE INDEX IDX_MON_METRIC_HIST_03 ON MON_METRIC_HIST (AGENT_ID, RECEIVED_AT);

CREATE INDEX IDX_MON_AGENT_HB_HIST_01 ON MON_AGENT_HEARTBEAT_HIST (SERVER_ID, COLLECTED_AT);
CREATE INDEX IDX_MON_AGENT_HB_HIST_02 ON MON_AGENT_HEARTBEAT_HIST (AGENT_ID, RECEIVED_AT);

CREATE INDEX IDX_MON_EVENT_01 ON MON_EVENT (STATUS_CODE, SEVERITY_CODE, FIRST_OCCURRED_AT);
CREATE INDEX IDX_MON_EVENT_02 ON MON_EVENT (SERVER_ID, FIRST_OCCURRED_AT);
CREATE INDEX IDX_MON_EVENT_03 ON MON_EVENT (INCIDENT_ID);

CREATE INDEX IDX_MON_INCIDENT_01 ON MON_INCIDENT (STATUS_CODE, DETECTED_AT);

CREATE INDEX IDX_SYS_AUDIT_LOG_01 ON SYS_AUDIT_LOG (USER_ID, CREATED_AT);
CREATE INDEX IDX_SYS_AUDIT_LOG_02 ON SYS_AUDIT_LOG (ACTION_TYPE, CREATED_AT);
CREATE INDEX IDX_SYS_AUDIT_LOG_03 ON SYS_AUDIT_LOG (TARGET_ID, CREATED_AT);

CREATE INDEX IDX_MON_LOG_ENTRY_01 ON MON_LOG_ENTRY (SERVER_ID, LOGGED_AT);
CREATE INDEX IDX_MON_LOG_ENTRY_02 ON MON_LOG_ENTRY (LOG_SOURCE_ID, LOGGED_AT);

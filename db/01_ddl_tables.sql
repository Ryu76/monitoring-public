-- Sequence and Trigger for SYS_USER
CREATE SEQUENCE SQ_SYS_USER START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE OR REPLACE TRIGGER TRG_SYS_USER
BEFORE INSERT ON SYS_USER
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT SQ_SYS_USER.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/


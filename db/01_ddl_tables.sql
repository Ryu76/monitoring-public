-- 범용 지표 이력 (Range Partitioning - 수집일 기준)
CREATE TABLE MON_METRIC_HIST (
    METRIC_HIST_ID      NUMBER(19) ,
    SERVER_ID           NUMBER(19) NOT NULL,
    AGENT_ID            NUMBER(19),
    METRIC_CODE         VARCHAR2(60 CHAR) NOT NULL,
    DIMENSION_KEY       VARCHAR2(60 CHAR),
    DIMENSION_VALUE     VARCHAR2(200 CHAR),
    METRIC_VALUE        NUMBER,
    STRING_VALUE        VARCHAR2(1000 CHAR),
    STATUS_CODE         VARCHAR2(30 CHAR),
    QUALITY_CODE        VARCHAR2(30 CHAR),
    COLLECTED_AT        TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    RECEIVED_AT         TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    BATCH_UID           VARCHAR2(40 CHAR)
) PARTITION BY RANGE (COLLECTED_AT) (
    PARTITION p_initial VALUES LESS THAN (TIMESTAMP '2025-01-01 00:00:00.000000 +00:00')
    -- 실제 운영에서는 파티션 관리 스크립트 또는 인터벌 파티션(Interval Partition)을 사용합니다.
    -- INTERVAL(NUMTOYMINTERVAL(1, 'MONTH'))
);

